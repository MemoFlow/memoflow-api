import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  PrimaryGeneratedColumn,
  UpdateDateColumn,
} from 'typeorm';

/** Must match the migration that created the column. */
export const SEARCH_VECTOR_EXPRESSION = `setweight(to_tsvector('simple', left(coalesce(title, ''), 1000)), 'A') || setweight(to_tsvector('simple', left(coalesce(content, ''), 100000)), 'B')`;

@Entity('sections')
@Index('IDX_sections_document_order', ['documentId', 'order'])
@Index('IDX_sections_search_vector', ['searchVector'], { type: 'gin' })
export class SectionOrmEntity {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Index()
  @Column({ type: 'uuid', name: 'document_id' })
  documentId: string;

  @Column({ type: 'varchar' })
  title: string;

  @Column({ type: 'text' })
  content: string;

  /**
   * Full-text vector, generated by Postgres from `title` (weight A, first
   * 1000 characters) and `content` (weight B, first 100000 characters: a tsvector has a hard size
   * limit). Declared only so `migration:generate` stays clean: it is never
   * selected (`select: false`) and never written (`insert`/`update: false`);
   * only the section retriever reads it, through raw SQL. `simple` because
   * documents can be in any language.
   */
  @Column({
    type: 'tsvector',
    name: 'search_vector',
    generatedType: 'STORED',
    asExpression: SEARCH_VECTOR_EXPRESSION,
    select: false,
    insert: false,
    update: false,
    nullable: true,
  })
  searchVector?: string;

  @Column({ type: 'int', name: 'order' })
  order: number;

  @Column({ type: 'varchar', default: 'draft' })
  status: string;

  @Column({ type: 'int', name: 'word_count', default: 0 })
  wordCount: number;

  @CreateDateColumn({ type: 'timestamptz', name: 'created_at' })
  createdAt: Date;

  @UpdateDateColumn({ type: 'timestamptz', name: 'updated_at' })
  updatedAt: Date;
}
